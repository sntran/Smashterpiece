export const STRINGS = { en, vi };

// Return the text for a key. Unknown keys and languages use English, then
// the key itself, so that the game never shows an empty button.
export function translate(lang, key, params = {}) {
  const table = STRINGS[lang] ?? en;
  let form = key;
  if (typeof params.count === 'number') {
    const plural = `${key}.${params.count === 1 ? 'one' : 'other'}`;
    if (plural in table || plural in en) form = plural;
  }
  const text = table[form] ?? en[form] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// Pick the language: the saved choice, else the first language of the
// device that the game knows, else English.
export function pickLanguage(saved, deviceLanguages = []) {
  if (LANGUAGES.includes(saved)) return saved;
  for (const tag of deviceLanguages) {
    const code = String(tag).toLowerCase().split('-')[0];
    if (LANGUAGES.includes(code)) return code;
  }
  return 'en';
}

// Return the placeholders of a text, sorted, for the tests.
export function placeholders(text) {
  return [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
}
